#!/usr/bin/env python3
"""Render usable-loop/v2 skill-local projections and runtime copies."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT_PATH = ROOT / "contracts" / "usable-loop-v2.json"
RUNTIME_PATH = ROOT / "runtime" / "handrails_state.py"
RUNTIME_SKILLS = {
    "branch-sandbox",
    "feedback-loop",
    "two-axis-review",
    "verify-before-claim",
}


def load_contract() -> dict[str, object]:
    value = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    if value.get("contract") != "usable-loop/v2":
        raise RuntimeError(f"unexpected contract in {CONTRACT_PATH}")
    return value


def _items(values: list[str]) -> str:
    return ", ".join(f"`{value}`" for value in values) if values else "None"


def _record_projection(name: str, record: dict[str, object]) -> list[str]:
    lines = [f"### `{name}`", ""]
    lines.append(f"Required: {_items(record.get('required_fields', []))}.")
    optional = record.get("optional_fields", [])
    if optional:
        lines.append("")
        lines.append(f"Optional: {_items(optional)}.")
    conditional = record.get("conditional_fields")
    if conditional:
        lines.extend(["", "Conditional fields:", "", "```json"])
        lines.append(json.dumps(conditional, sort_keys=True, indent=2))
        lines.append("```")
    return lines


def render_reference(skill_name: str, contract: dict[str, object]) -> str:
    skill = contract["skills"][skill_name]
    policies = contract["policies"]
    record_names = list(
        dict.fromkeys(skill["consumes"] + skill["produces"] + skill.get("optional_produces", []))
    )
    lines = [
        "<!-- Generated by scripts/render_contract.py; do not edit. -->",
        "# usable-loop/v2 local contract",
        "",
        f"Skill: `{skill_name}`  ",
        f"Role: `{skill['role']}`",
        "",
        f"Consumes: {_items(skill['consumes'])}.  ",
        f"Produces: {_items(skill['produces'])}.  ",
        f"Optional on continuity trigger: {_items(skill.get('optional_produces', []))}.",
        "",
        "## Outcome Reference",
        "",
        "```text",
        "Contract: usable-loop/v2",
        "Task ID:",
        "Outcome Source kind: request | conversation | alignment-snapshot | issue | prd | spec | bug-repro | deployment-objective | other",
        "Outcome Source ID:",
        "Outcome Source locator:",
        "Outcome Revision:",
        "Revision basis:",
        "Outcome Authority: authoritative | provisional",
        "Authority basis:",
        "Outcome lifecycle: active | superseded",
        "Outcome snapshot:",
        "Outcome currentness: fresh | stale",
        "Supersedes, if any:",
        "Stale when:",
        "```",
        "",
        "A current user request is authoritative when the user controls the scope",
        "and no permission or designated-source conflict exists. Agent-derived or",
        "reinterpreted meaning is provisional. Preserve Task ID across revisions.",
        "Use an opaque revision such as `r1` unless canonical bytes were hashed.",
        "",
        "## Invalidation",
        "",
        "Any Outcome Revision, Boundary Digest, relevant code-state, or relevant",
        "environment change makes dependent evidence, review, and claims stale.",
        "Do not reuse old evidence after an unrelatedness argument in v2; rerun the",
        "narrowest relevant check.",
        "",
        "## Checkpoint projection",
        "",
        "Default to a compact direct result. Expand the shared Checkpoint only for",
        "pause/block, cross-session or agent handoff, context-compaction risk,",
        "expensive/non-repeatable evidence, or explicit handoff request. If local",
        "persistence is needed, rewrite the one `.scratch/<task-id>/STATE.md` Capsule.",
        "It is an orientation cache, never authority or fresh evidence.",
        "On resume, first reconcile the designated Outcome Source/Revision, then",
        "read the Capsule for orientation, then recapture participating state.",
        "",
        "Checkpoint fields: `task_id`, `outcome_reference`, `boundary_and_state`,",
        "`done`, `next`, `blockers`, `decision_delta`, `evidence_delta`,",
        "`supported_claims`, `still_unverified`, `stale_when`.",
        "",
    ]
    if skill["runtime_required"]:
        lines.extend(
            [
                "## Deterministic state runtime",
                "",
                "Use the `scripts/handrails_state.py` beside this Skill, resolving",
                "the path from this installed `SKILL.md` rather than the project cwd.",
                "In the Agent Handrails source repository, the canonical equivalent is",
                "`runtime/handrails_state.py`. Its interface is:",
                "",
                "```text",
                "inventory",
                "confirm --kind claim|review --classifications <file|->",
                "capture --boundary <confirmed-boundary.json>",
                "```",
                "",
                "Only classify runtime-generated Candidate/Hunk IDs. Every logical",
                "unit needs one classification, a rationale, and `authorized |",
                "needs-authorization | not-applicable`. Never invent or pass a naked",
                "digest. Missing units, authorization conflicts, drift, and digest",
                "mismatch block the operation.",
                "",
            ]
        )
    if skill_name == "verify-before-claim":
        routing = policies["claim-routing"]
        lines.extend(
            [
                "## Claim routing",
                "",
                f"- `fact`: {routing['fact']}.",
                f"- `scoped-task`: {routing['scoped-task']}.",
                f"- `high-assurance`: {routing['high-assurance']}.",
                "",
                "Fact output is at most 12 lines; scoped-task output is at most 30",
                "lines unless the user explicitly asks for full records.",
                "",
            ]
        )
    if skill_name == "feedback-loop":
        lines.extend(
            [
                "## Evidence ownership",
                "",
                "This skill emits development evidence only. `observed` guides the",
                "next development move but cannot support a completion claim. There is",
                "no verify-to-feedback backflow requirement.",
                "",
            ]
        )
    if skill_name == "two-axis-review":
        lines.extend(
            [
                "## Review ownership",
                "",
                "This skill owns semantic Outcome Fit and Engineering Quality judgment.",
                "The runtime owns inventory, canonicalization, digest, and drift checks.",
                "A high-assurance claim consumes the resulting exact Review Record.",
                "",
            ]
        )
    if skill_name == "branch-sandbox":
        operations = policies["destructive-operations"]["explicit_authorization_required"]
        lines.extend(
            [
                "## Destructive operations",
                "",
                f"Explicit authorization is required for {_items(operations)}.",
                "By default report cleanup commands without executing them.",
                "",
            ]
        )
    lines.extend(["## Record shapes", ""])
    records = contract["records"]
    for record_name in record_names:
        lines.extend(_record_projection(record_name, records[record_name]))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generated_files(contract: dict[str, object]) -> dict[Path, bytes]:
    result: dict[Path, bytes] = {}
    runtime = RUNTIME_PATH.read_bytes()
    for skill_name in contract["managed_skills"]:
        skill_root = ROOT / "skills" / skill_name
        result[skill_root / "references" / "usable-loop-v2.md"] = render_reference(
            skill_name, contract
        ).encode("utf-8")
        if skill_name in RUNTIME_SKILLS:
            result[skill_root / "scripts" / "handrails_state.py"] = runtime
    return result


def apply(files: dict[Path, bytes]) -> None:
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        if path.name == "handrails_state.py":
            path.chmod(0o755)


def check(files: dict[Path, bytes]) -> list[Path]:
    return [
        path
        for path, expected in files.items()
        if not path.is_file() or path.read_bytes() != expected
    ]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--check", action="store_true")
    return parser.parse_args()


def main() -> int:
    arguments = parse_args()
    contract = load_contract()
    files = generated_files(contract)
    if arguments.apply:
        apply(files)
        print(f"Rendered {len(files)} usable-loop/v2 projections")
        return 0
    drift = check(files)
    if drift:
        for path in drift:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    print(f"usable-loop/v2 projections are current ({len(files)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
